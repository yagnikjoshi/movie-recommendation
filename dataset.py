def get_movie_data():
    """Return pandas DataFrame with weighted combined features from both Indian and Hollywood datasets."""
    import os
    
    # 1. Load Indian Movies
    df_indian = pd.DataFrame(MOVIES_DATA)
    
    # 2. Load Hollywood Movies (IMDB Top 1000)
    csv_path = os.path.join(os.path.dirname(__file__), 'imdb_test.csv')
    if os.path.exists(csv_path):
        df_hw = pd.read_csv(csv_path)
        # Rename columns to match schema
        rename_map = {
            'Title': 'title',
            'Genre': 'genres',
            'Description': 'overview',
            'Director': 'director',
            'Actors': 'cast',
            'Year': 'release_year',
            'Runtime (Minutes)': 'runtime',
            'Rating': 'vote_average',
            'Votes': 'vote_count'
        }
        df_hw = df_hw.rename(columns=rename_map)
        
        # Add missing columns
        df_hw['industry'] = 'Hollywood'
        df_hw['language'] = 'English'
        df_hw['keywords'] = df_hw['genres'].fillna('') # Use genres as keywords for fallback
        df_hw['poster_path'] = 'https://images.unsplash.com/photo-1536440136628-849c177e76a1?w=500&auto=format&fit=crop&q=80'
        df_hw['id'] = range(1000, 1000 + len(df_hw))
        
        # Keep only required columns
        req_cols = ['id', 'title', 'release_year', 'genres', 'industry', 'language', 
                    'director', 'cast', 'vote_average', 'vote_count', 'runtime', 
                    'overview', 'keywords', 'poster_path']
        df_hw = df_hw[req_cols]
        
        # Merge both
        df = pd.concat([df_indian, df_hw], ignore_index=True)
    else:
        df = df_indian
        
    df.fillna('', inplace=True)
    # Ensure numeric types
    df['vote_average'] = pd.to_numeric(df['vote_average'], errors='coerce').fillna(0.0)
    df['vote_count'] = pd.to_numeric(df['vote_count'], errors='coerce').fillna(0)
    df['runtime'] = pd.to_numeric(df['runtime'], errors='coerce').fillna(120)
    df['release_year'] = pd.to_numeric(df['release_year'], errors='coerce').fillna(2000)

    # 3. Create combined features for TF-IDF
    df['combined_features'] = (
        (df['genres'].str.replace(',', ' ') + ' ') * 4 +
        (df['industry'] + ' ') * 3 +
        (df['keywords'] + ' ') * 3 +
        (df['director'] + ' ') * 2 +
        (df['cast'].str.replace(',', ' ') + ' ') * 2 +
        df['overview'] + ' ' +
        df['title']
    )
    return df

def get_all_genres(df):
    genres_set = set()
    for gs in df['genres'].dropna():
        for g in gs.split(','):
            genres_set.add(g.strip())
    return sorted(list(genres_set))

def get_all_industries(df):
    return sorted(df['industry'].dropna().unique().tolist())

def get_all_languages(df):
    return sorted(df['language'].dropna().unique().tolist())
